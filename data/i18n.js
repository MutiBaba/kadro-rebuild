const I18N_LANGS = [
  { code: "tr", flag: "🇹🇷", label: "Türkçe" },
  { code: "en", flag: "🇬🇧", label: "English" },
  { code: "es", flag: "🇪🇸", label: "Español" },
  { code: "de", flag: "🇩🇪", label: "Deutsch" },
  { code: "fr", flag: "🇫🇷", label: "Français" }
];

const I18N_DEFAULT_LANG = "tr";
const I18N_STORAGE_KEY = "rb11_lang";

let currentLang = I18N_DEFAULT_LANG;
try {
  const stored = localStorage.getItem(I18N_STORAGE_KEY);
  if (stored && I18N[stored]) currentLang = stored;
} catch (e) { /* localStorage kapalı olabilir (private mode) — varsayılan dilde devam */ }

// t("key", { name: "X" }) → çeviri + placeholder ikamesi.
// Anahtar aktif dilde yoksa Türkçeye, o da yoksa anahtarın kendisine düşer.
function t(key, vars) {
  const dict = I18N[currentLang] || I18N[I18N_DEFAULT_LANG];
  let str = dict[key];
  if (str === undefined) str = I18N[I18N_DEFAULT_LANG][key];
  if (str === undefined) return key;
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (m, name) => (vars[name] !== undefined ? String(vars[name]) : m));
}

function getLang() { return currentLang; }

const i18nListeners = [];
function onLangChange(fn) { i18nListeners.push(fn); }

function setLang(code) {
  if (!I18N[code] || code === currentLang) return;
  currentLang = code;
  try { localStorage.setItem(I18N_STORAGE_KEY, code); } catch (e) { /* yoksayılır */ }
  applyI18n();
}

// data-i18n* işaretli TÜM statik DOM düğümlerini tazeler, sonra dinamik ekran
// yeniden çizicilerini (game.js / multiplayer.js kaydeder) çağırır.
function applyI18n() {
  document.documentElement.lang = currentLang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  const titleEl = document.querySelector("title");
  if (titleEl) titleEl.textContent = t("app.title");
  for (const fn of i18nListeners) {
    try { fn(); } catch (e) { console.error("i18n rerender failed", e); }
  }
}
